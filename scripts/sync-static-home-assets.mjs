import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import { currentCss, staticHomeInputHash } from "./static-home-assets-lib.mjs";
import { staticHomeFontClasses, staticHomeFontHashes } from "./static-home-fonts.mjs";

const inputHash = staticHomeInputHash();
const asset = await currentCss();
mkdirSync("public", { recursive: true });
for (const file of readdirSync("public")) {
  if (/^static-home\.[a-f0-9]{16}\.(?:css|html)$/.test(file)) rmSync(`public/${file}`);
}
writeFileSync(`public${asset.publicPath}`, asset.content);
const canonicalCandidate = process.env.NEXT_PUBLIC_SITE_URL ?? process.env.VERCEL_PROJECT_PRODUCTION_URL ?? "https://steve-defendre-portfolio.vercel.app";
const canonical = new URL("/", /^[a-z][a-z\d+\-.]*:\/\//i.test(canonicalCandidate) ? canonicalCandidate : `https://${canonicalCandidate}`).toString();
const temp = mkdtempSync(join(tmpdir(), "static-home-render-"));
const bundle = join(temp, "render.cjs");
await build({ entryPoints: ["scripts/render-static-home.tsx"], outfile: bundle, bundle: true, platform: "node", format: "cjs", tsconfig: "tsconfig.json" });
const renderer = await import(pathToFileURL(bundle).href);
const html = renderer.renderStaticHomeDocument(asset.publicPath, staticHomeFontClasses, canonical);
const htmlSha256 = createHash("sha256").update(html).digest("hex");
const htmlPath = `/static-home.${htmlSha256.slice(0, 16)}.html`;
writeFileSync(`public${htmlPath}`, html);
rmSync(temp, { recursive: true });
mkdirSync("src/generated", { recursive: true });
const outputManifest = {
  inputSha256: inputHash,
  css: { path: asset.publicPath, sha256: asset.hash },
  html: { path: htmlPath, sha256: htmlSha256, cssSha256: asset.hash },
  fonts: staticHomeFontHashes(),
};
writeFileSync("src/generated/static-home-assets.ts", `// Generated by scripts/sync-static-home-assets.mjs\nexport const staticHomeInputHash = ${JSON.stringify(inputHash)};\nexport const staticHomeCss = ${JSON.stringify(asset.publicPath)};\nexport const staticHomeCssHash = ${JSON.stringify(asset.hash)};\nexport const staticHomeHtml = ${JSON.stringify(htmlPath)};\nexport const staticHomeHtmlHash = ${JSON.stringify(htmlSha256)};\nexport const staticHomeOutputManifest = ${JSON.stringify(outputManifest)} as const;\n`);
console.log(`Synced ${asset.publicPath} and ${htmlPath}`);
