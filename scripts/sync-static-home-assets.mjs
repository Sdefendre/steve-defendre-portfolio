import nextEnv from "@next/env";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { resolveSiteUrl } from "../src/lib/site-url.mjs";
import { build } from "esbuild";
import { assertStaticHomeRuntime, currentCss, staticHomeInputHash } from "./static-home-assets-lib.mjs";
import { staticHomeFontClasses, staticHomeFontHashes } from "./static-home-fonts.mjs";

// Match the production build when canonical configuration lives in .env files.
nextEnv.loadEnvConfig(process.cwd());

const inputHash = staticHomeInputHash();
const asset = await currentCss();
const canonical = resolveSiteUrl().href;
const temp = mkdtempSync(join(tmpdir(), "static-home-render-"));
let html;
try {
  const bundle = join(temp, "render.cjs");
  await build({ entryPoints: ["scripts/render-static-home.tsx"], outfile: bundle, bundle: true, platform: "node", format: "cjs", tsconfig: "tsconfig.json" });
  const renderer = await import(pathToFileURL(bundle).href);
  html = renderer.renderStaticHomeDocument(asset.publicPath, staticHomeFontClasses, canonical);
  assertStaticHomeRuntime(html, asset.publicPath);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
const htmlSha256 = createHash("sha256").update(html).digest("hex");
const htmlPath = `/static-home.${htmlSha256.slice(0, 16)}.html`;
const outputManifest = {
  inputSha256: inputHash,
  css: { path: asset.publicPath, sha256: asset.hash },
  html: { path: htmlPath, sha256: htmlSha256, cssSha256: asset.hash },
  fonts: staticHomeFontHashes(),
};
const manifest = `// Generated by scripts/sync-static-home-assets.mjs\nexport const staticHomeInputHash = ${JSON.stringify(inputHash)};\nexport const staticHomeCss = ${JSON.stringify(asset.publicPath)};\nexport const staticHomeCssHash = ${JSON.stringify(asset.hash)};\nexport const staticHomeHtml = ${JSON.stringify(htmlPath)};\nexport const staticHomeHtmlHash = ${JSON.stringify(htmlSha256)};\nexport const staticHomeOutputManifest = ${JSON.stringify(outputManifest)} as const;\n`;

// Stage every output on the destination filesystem. Publish the content-addressed
// assets first, then atomically replace the manifest as the commit point. Until
// then, the previous manifest and every asset it references remain usable.
mkdirSync("public", { recursive: true });
mkdirSync("src/generated", { recursive: true });
const staging = mkdtempSync("src/generated/.static-home-stage-");
try {
  writeFileSync(join(staging, "style.css"), asset.content);
  writeFileSync(join(staging, "document.html"), html);
  writeFileSync(join(staging, "manifest.ts"), manifest);
  renameSync(join(staging, "style.css"), `public${asset.publicPath}`);
  renameSync(join(staging, "document.html"), `public${htmlPath}`);
  renameSync(join(staging, "manifest.ts"), "src/generated/static-home-assets.ts");
} finally {
  rmSync(staging, { recursive: true, force: true });
}

// Retire superseded outputs only after the replacement manifest is in place.
for (const file of readdirSync("public")) {
  if (/^static-home\.[a-f0-9]{16}\.(?:css|html)$/.test(file) && ![asset.publicPath, htmlPath].includes(`/${file}`)) {
    rmSync(`public/${file}`);
  }
}
console.log(`Synced ${asset.publicPath} and ${htmlPath}`);
